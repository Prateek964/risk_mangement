def spiral(cx, cy, r, turns, rot):
    pts = []
    n = int(18 * turns)
    for i in range(n + 1):
        t = i / n
        a = rot + t * turns * 2 * math.pi
        rr = r * (0.8 + 0.2 * t)
        pts.append((cx + rr * math.cos(a), cy + rr * 0.85 * math.sin(a)))
    d = f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"
    for x, y in pts[1:]:
        d += f" L{x:.1f},{y:.1f}"
    return d


