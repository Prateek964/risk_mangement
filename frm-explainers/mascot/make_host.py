def brow(x0, x1, y_at, sign):
    out = []
    for i in range(70):
        t = rnd.random()
        x = x0 + (x1 - x0) * t
        y = y_at(t) + rnd.uniform(-5, 5) * (1 - abs(t - .4))
        ln = rnd.uniform(9, 16)
        ang = math.radians(rnd.uniform(188, 205)) if sign > 0 else math.radians(rnd.uniform(-25, -8))
        out.append(f'<path d="M{x:.1f},{y + 4:.1f} l{ln * math.cos(ang):.1f},{ln * math.sin(ang):.1f}" '
                   f'stroke="{rnd.choice(["#120c0a", "#1f1613", "#2b1f1b"])}" stroke-width="{rnd.uniform(1.6, 2.8):.1f}"/>')
    return "".join(out)


